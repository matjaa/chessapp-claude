#pragma once

#include "core/Types.hpp"

#include <array>
#include <cstdint>
#include <string>
#include <string_view>

namespace chess
{
// A chess position: piece placement, side to move, castling rights,
// en passant square and move counters. Moves are applied with makeMove();
// to "undo" a move, keep a copy of the position from before it.
class Position
{
public:
    static constexpr const char* StartFen = "rnbqkbnr/pppppppp/8/8/8/8/PPPPPPPP/RNBQKBNR w KQkq - 0 1";

    // The standard starting position.
    Position();

    // Builds a position from Forsyth-Edwards Notation. Throws
    // std::invalid_argument if the text is not a valid FEN.
    static Position fromFen(std::string_view fen);
    std::string toFen() const;

    // --- Queries -----------------------------------------------------------
    Piece pieceAt(Square sq) const { return m_board[static_cast<std::size_t>(sq)]; }
    Color sideToMove() const { return m_sideToMove; }
    int castlingRights() const { return m_castling; }
    Square enPassantSquare() const { return m_enPassant; } // NoSquare if none
    int halfmoveClock() const { return m_halfmoveClock; }  // for the fifty-move rule
    int fullmoveNumber() const { return m_fullmoveNumber; }
    Square kingSquare(Color c) const { return m_kingSquare[static_cast<std::size_t>(index(c))]; }

    // Zobrist hash of the position. Two positions that are the same for the
    // repetition rule (same pieces, side to move, castling rights and en
    // passant possibility) have the same hash.
    std::uint64_t hash() const { return m_hash; }
    // Recomputes the hash from scratch (used by tests to check hash()).
    std::uint64_t computeHash() const;

    bool isSquareAttacked(Square sq, Color byColor) const;
    bool inCheck() const { return isSquareAttacked(kingSquare(m_sideToMove), ~m_sideToMove); }

    // True if neither side can ever checkmate: K vs K, K+B vs K, K+N vs K,
    // or kings plus bishops that all stand on squares of one colour.
    bool isInsufficientMaterial() const;

    // --- Moves -------------------------------------------------------------
    // Moves that follow the piece movement rules, ignoring whether they
    // leave the own king in check (castling is only generated when legal).
    void generatePseudoLegalMoves(MoveList& moves) const;
    // Fully legal moves.
    void generateLegalMoves(MoveList& moves) const;
    // True if the pseudo-legal move does not leave the mover's king in check.
    bool isLegal(const Move& move) const;

    // Applies a move generated by generatePseudoLegalMoves/generateLegalMoves.
    void makeMove(const Move& move);

private:
    struct EmptyTag
    {
    };
    explicit Position(EmptyTag) {} // empty board, used by fromFen

    void clear();
    void putPiece(Square sq, Piece piece);
    void removePiece(Square sq);
    bool hasLegalEnPassantCapture(Square epSquare) const;

    void generatePawnMoves(Square from, MoveList& moves) const;
    void generateStepMoves(Square from, const std::array<Square, 8>& targets, int count, MoveList& moves) const;
    void generateSlidingMoves(Square from, bool diagonal, bool straight, MoveList& moves) const;
    void generateCastlingMoves(MoveList& moves) const;

    std::array<Piece, 64> m_board{};
    std::array<Square, 2> m_kingSquare{NoSquare, NoSquare};
    Color                 m_sideToMove     = Color::White;
    int                   m_castling       = NoCastling;
    Square                m_enPassant      = NoSquare;
    int                   m_halfmoveClock  = 0;
    int                   m_fullmoveNumber = 1;
    std::uint64_t         m_hash           = 0;
};
} // namespace chess
